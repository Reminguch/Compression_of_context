class TensorOperations:
    def __init__(self):
        pass

    def tensor_addition(self, tensor1, tensor2):
        return tensor1 + tensor2

    def tensor_subtraction(self, tensor1, tensor2):
        return tensor1 - tensor2

    def tensor_multiplication(self, tensor1, tensor2):
        return tensor1 * tensor2

    def tensor_division(self, tensor1, tensor2):
        return tensor1 / tensor2
